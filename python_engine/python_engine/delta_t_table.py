"""ΔT (TT − UT) table exported for the Dart engine in mobile/.

Positions depend on Terrestrial Time while events are reckoned in UT; the two
engines must agree on the gap or every instant drifts (the Phase 0 spike saw
up to 12 s of tithi error with a different ΔT model). The table samples
Swiss Ephemeris quarterly; linear interpolation is good to well under 0.01 s.
"""

from __future__ import annotations

from pathlib import Path

import swisseph

FIRST_YEAR = 2014
LAST_YEAR = 2042

DART_TABLE_PATH = (
    Path(__file__).resolve().parents[2]
    / "mobile" / "packages" / "panchang_engine" / "lib" / "src" / "time" / "delta_t_table.g.dart"
)


def delta_t_table() -> list[tuple[float, float]]:
    """(Julian Day UT, ΔT seconds) on the first day of every quarter, inclusive of LAST_YEAR-01-01."""
    quarters = [
        (year, month)
        for year in range(FIRST_YEAR, LAST_YEAR)
        for month in (1, 4, 7, 10)
    ] + [(LAST_YEAR, 1)]
    jds = [swisseph.julday(year, month, 1, 0.0) for year, month in quarters]
    return [(jd, swisseph.deltat(jd) * 86400.0) for jd in jds]


def render_dart(table: list[tuple[float, float]]) -> str:
    rows = "\n".join(f"  ({jd!r}, {seconds!r})," for jd, seconds in table)
    return (
        "// GENERATED by python_engine/python_engine/scripts/export_delta_t.py — do not edit.\n"
        f"// Swiss Ephemeris {swisseph.version} ΔT, quarterly {FIRST_YEAR}–{LAST_YEAR}.\n"
        "\n"
        "/// (Julian Day UT, ΔT seconds), ascending.\n"
        "const List<(double, double)> deltaTTable = [\n"
        f"{rows}\n"
        "];\n"
    )


def write_dart_table(path: Path = DART_TABLE_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_dart(delta_t_table()), encoding="utf-8", newline="\n")
    return path
