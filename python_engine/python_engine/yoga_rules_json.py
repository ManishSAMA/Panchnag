"""The yoga rules as JSON, shared with the Dart engine in mobile/.

yoga_rules.py remains where yogas are edited. shared/yoga_rules.json is
generated from it (scripts/export_yoga_rules.py) and a test fails when the
two drift apart. JSON has no int keys or tuples, so weekday keys become
strings ("0" = Sunday) and a (ghati, pala) varjya becomes a two-item list.
"""

from __future__ import annotations

import json
from pathlib import Path

from yoga_rules import AANANDADI_YOGAS, DAINIKA_RULES

# Bump when the document's shape changes, so the Dart side can refuse a stale file.
SCHEMA_VERSION = 1

_REPO = Path(__file__).resolve().parents[2]
YOGA_RULES_JSON_PATH = _REPO / "shared" / "yoga_rules.json"
YOGA_RULES_DART_PATH = _REPO / "mobile/packages/panchang_engine/lib/src/panchang/yoga_rules.g.dart"


def _aanandadi(yoga: dict) -> dict:
    varjya = yoga["varjya"]
    return {**yoga, "varjya": list(varjya) if isinstance(varjya, tuple) else varjya}


def _dainika(rule: dict) -> dict:
    return {**rule, "vara_map": {str(vara): values for vara, values in rule["vara_map"].items()}}


def yoga_rules_document() -> dict:
    return {
        "schema_version": SCHEMA_VERSION,
        "aanandadi": [_aanandadi(y) for y in AANANDADI_YOGAS],
        "dainika": [_dainika(r) for r in DAINIKA_RULES],
    }


def _json_text() -> str:
    # Indented and sorted: the file is committed, so diffs stay readable.
    return json.dumps(yoga_rules_document(), indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def write_yoga_rules_json(path: Path = YOGA_RULES_JSON_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_json_text(), encoding="utf-8", newline="\n")
    return path


def write_yoga_rules_dart(path: Path = YOGA_RULES_DART_PATH) -> Path:
    """The same JSON text as a Dart constant, so the engine needs no asset."""
    source = (
        "// GENERATED by python_engine/python_engine/scripts/export_yoga_rules.py — do not edit.\n"
        "// The yoga rules of yoga_rules.py; shared/yoga_rules.json holds the same text.\n\n"
        f"const String yogaRulesJson = r'''\n{_json_text()}''';\n"
    )
    path.write_text(source, encoding="utf-8", newline="\n")
    return path
