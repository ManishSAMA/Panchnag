"""The yoga rules, shared with the Dart engine as one JSON file.

yoga_rules.py stays the place yogas are edited; shared/yoga_rules.json is
generated from it so the mobile app's Muhurat section matches the same rules.
Design: plans/muhurat-section.md (Phase 3).
"""

from __future__ import annotations

import json

from yoga_rules import AANANDADI_YOGAS, DAINIKA_RULES
from yoga_rules_json import (
    SCHEMA_VERSION,
    YOGA_RULES_DART_PATH,
    YOGA_RULES_JSON_PATH,
    write_yoga_rules_dart,
    write_yoga_rules_json,
    yoga_rules_document,
)


def test_document_holds_every_rule_in_order():
    document = yoga_rules_document()

    assert document["schema_version"] == SCHEMA_VERSION
    assert [y["name"] for y in document["aanandadi"]] == [y["name"] for y in AANANDADI_YOGAS]
    assert [r["name"] for r in document["dainika"]] == [r["name"] for r in DAINIKA_RULES]


def test_weekday_keys_and_varjya_survive_the_json_round_trip():
    document = yoga_rules_document()

    assert json.loads(json.dumps(document)) == document
    for rule, source in zip(document["dainika"], DAINIKA_RULES, strict=True):
        assert {int(vara): values for vara, values in rule["vara_map"].items()} == source["vara_map"]
    for yoga, source in zip(document["aanandadi"], AANANDADI_YOGAS, strict=True):
        varjya = source["varjya"]
        assert yoga["varjya"] == (list(varjya) if isinstance(varjya, tuple) else varjya)


def test_written_file_reads_back_as_the_document(tmp_path):
    path = write_yoga_rules_json(tmp_path / "yoga_rules.json")

    assert json.loads(path.read_text(encoding="utf-8")) == yoga_rules_document()


def test_rewriting_is_byte_identical(tmp_path):
    first = write_yoga_rules_json(tmp_path / "a.json").read_bytes()
    second = write_yoga_rules_json(tmp_path / "b.json").read_bytes()

    assert first == second


def test_shared_file_is_up_to_date_with_yoga_rules_py():
    committed = json.loads(YOGA_RULES_JSON_PATH.read_text(encoding="utf-8"))

    assert committed == yoga_rules_document(), (
        "shared/yoga_rules.json is stale: run "
        "`python scripts/export_yoga_rules.py` and commit the result."
    )


def test_dart_source_holds_the_json_text(tmp_path):
    json_text = write_yoga_rules_json(tmp_path / "yoga_rules.json").read_text(encoding="utf-8")
    dart_text = write_yoga_rules_dart(tmp_path / "yoga_rules.g.dart").read_text(encoding="utf-8")

    assert f"r'''\n{json_text}'''" in dart_text
    assert dart_text.startswith("// GENERATED by python_engine/python_engine/scripts/export_yoga_rules.py")


def test_dart_engine_file_is_up_to_date_with_yoga_rules_py(tmp_path):
    fresh = write_yoga_rules_dart(tmp_path / "yoga_rules.g.dart").read_text(encoding="utf-8")

    assert YOGA_RULES_DART_PATH.read_text(encoding="utf-8") == fresh, (
        "yoga_rules.g.dart is stale: run `python scripts/export_yoga_rules.py` and commit the result."
    )
