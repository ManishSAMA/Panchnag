"""ΔT (TT − UT) for the Dart engine, exported from the reference so both
engines share one time scale. Design: plans/mobile-phase2-dart-engine.md."""

from __future__ import annotations

import swisseph as swe

from delta_t_table import DART_TABLE_PATH, delta_t_table, render_dart


def test_samples_quarterly_from_2014_through_2042():
    table = delta_t_table()
    jds = [jd for jd, _ in table]

    assert jds[0] == swe.julday(2014, 1, 1, 0.0)
    assert jds[-1] == swe.julday(2042, 1, 1, 0.0)
    assert len(jds) == (2042 - 2014) * 4 + 1
    assert jds == sorted(jds)


def test_values_are_swiss_ephemeris_delta_t_in_seconds():
    for jd, seconds in delta_t_table():
        assert seconds == swe.deltat(jd) * 86400.0


def test_linear_interpolation_between_samples_is_within_a_hundredth_of_a_second():
    table = delta_t_table()
    (jd0, dt0), (jd1, dt1) = table[40], table[41]
    mid = (jd0 + jd1) / 2

    assert abs((dt0 + dt1) / 2 - swe.deltat(mid) * 86400.0) < 0.01


def test_rendered_dart_holds_every_sample_exactly():
    text = render_dart(delta_t_table())

    assert text.startswith("// GENERATED by python_engine/python_engine/scripts/export_delta_t.py")
    for jd, seconds in delta_t_table():
        assert f"({jd!r}, {seconds!r})" in text


def test_committed_dart_table_is_up_to_date():
    assert DART_TABLE_PATH.read_text(encoding="utf-8") == render_dart(delta_t_table()), (
        "delta_t_table.g.dart is stale: run `python scripts/export_delta_t.py`."
    )
