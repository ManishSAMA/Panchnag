// The upload key lives outside git (see mobile/app/RELEASE.md). Without
// key.properties, release builds fall back to the debug key so CI and
// contributors can still build; Play rejects debug-signed bundles.
val keystorePropertiesFile = rootProject.file("key.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasUploadKey = keystorePropertiesFile.exists()

fun keystoreProperty(name: String): String =
    requireNotNull(keystoreProperties.getProperty(name)?.takeIf { it.isNotBlank() }) {
        "${keystorePropertiesFile.path} is missing $name"
    }

android {
    namespace = "io.github.manishsama.jainpanchang"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        // Fixed forever once the app is on Play.
        applicationId = "io.github.manishsama.jainpanchang"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        // Uses the version code from pubspec.yaml. When using split APKs, 1000 * ABI_VERSION
        // is added automatically by Flutter. (https://developer.android.com/studio/build/configure-apk-splits#configure-APK-versions)
        // You can force using the value of versionCode by specifying the `-P force-version-code-ignoring-abi=true`
        // flag during build.
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    signingConfigs {
        if (hasUploadKey) {
            create("release") {
                storeFile = file(keystoreProperty("storeFile"))
                storePassword = keystoreProperty("storePassword")
                keyAlias = keystoreProperty("keyAlias")
                keyPassword = keystoreProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // The Flutter Gradle plugin turns on R8 minify and resource
            // shrinking for release builds.
            signingConfig = if (hasUploadKey) {
                signingConfigs.getByName("release")
            } else {
                logger.warn("key.properties not found: signing the release build with the debug key.")
                signingConfigs.getByName("debug")
            }
        }
    }
}

