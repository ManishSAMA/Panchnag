"""Vendor ephemeris *data* from the persis_times package (MIT) into Dart tables.

Only coefficients are copied; the evaluation code in lib/src/astro/ is our own.
Re-run only to re-vendor from a newer persis_times:

    python tool/vendor_persis.py <path to persis_times-x.y.z>

Outputs (committed): lib/src/astro/vsop87d_earth.g.dart, lib/src/astro/nutation_iau2000b.g.dart
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
ASTRO = PACKAGE / "lib" / "src" / "astro"

NUMBER = r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?"
ROW = re.compile(rf"\[\s*({NUMBER})\s*,\s*({NUMBER})\s*,\s*({NUMBER})\s*\]")
ARGS = r"\((-?\d+) \* l \+ (-?\d+) \* lp \+ (-?\d+) \* f \+ (-?\d+) \* d \+ (-?\d+) \* om\)"
PSI_TERM = re.compile(
    rf"\(({NUMBER}) \+ ({NUMBER}) \* t\) \*\s*sin{ARGS} \+\s*({NUMBER}) \* cos{ARGS};"
)
EPS_TERM = re.compile(
    rf"\(({NUMBER}) \+ ({NUMBER}) \* t\) \*\s*cos{ARGS} \+\s*({NUMBER}) \* sin{ARGS};"
)


def _header(source: Path) -> str:
    license_text = (source / "LICENSE").read_text(encoding="utf-8").strip()
    notice = "\n".join(f"// {line}".rstrip() for line in license_text.splitlines())
    return (
        "// GENERATED by tool/vendor_persis.py from persis_times — do not edit.\n"
        "//\n"
        f"{notice}\n\n"
    )


def _rows(path: Path) -> list[tuple[str, str, str]]:
    return ROW.findall(path.read_text(encoding="utf-8"))


def vsop87d_earth(source: Path) -> str:
    data = source / "lib" / "src" / "data"
    blocks = []
    for coordinate, powers in (("l", 6), ("b", 5), ("r", 6)):
        series = []
        for power in range(powers):
            rows = _rows(data / f"sun_data_{coordinate}0{power}.dart")
            assert rows, f"no rows in {coordinate}0{power}"
            series.append("  [\n" + "".join(f"    ({a}, {b}, {c}),\n" for a, b, c in rows) + "  ],\n")
        blocks.append(
            f"/// VSOP87D Earth {coordinate.upper()}0..{coordinate.upper()}{powers - 1}: (A, B, C) for A·cos(B + C·τ).\n"
            f"const List<List<(double, double, double)>> earth{coordinate.upper()} = [\n"
            + "".join(series)
            + "];\n"
        )
    return _header(source) + "\n".join(blocks)


def nutation_terms(source: Path) -> str:
    text = (source / "lib" / "src" / "core" / "astronomy" / "nutation.dart").read_text(encoding="utf-8")
    psi_body, eps_body = text.split("double nutationInObliquity", 1)
    psi = PSI_TERM.findall(psi_body)
    eps = EPS_TERM.findall(eps_body)
    assert len(psi) == len(eps) == 77, (len(psi), len(eps))
    rows = []
    for p, e in zip(psi, eps):
        args_psi, args_eps = p[2:7], e[2:7]
        assert args_psi == p[8:13] and args_eps == e[8:13] and args_psi == args_eps
        rows.append(
            f"  ({', '.join(args_psi)}, {p[0]}, {p[1]}, {p[7]}, {e[0]}, {e[1]}, {e[7]}),\n"
        )
    return (
        _header(source)
        + "/// IAU 2000B lunisolar nutation, 0.1 µas units:\n"
        + "/// (l, l', F, D, Ω, ψ_sin, ψ_sin·t, ψ_cos, ε_cos, ε_cos·t, ε_sin).\n"
        + "const List<(int, int, int, int, int, double, double, double, double, double, double)>"
        + " nutationTerms = [\n"
        + "".join(rows)
        + "];\n"
    )


def main(source: Path) -> None:
    ASTRO.mkdir(parents=True, exist_ok=True)
    for name, text in (
        ("vsop87d_earth.g.dart", vsop87d_earth(source)),
        ("nutation_iau2000b.g.dart", nutation_terms(source)),
    ):
        (ASTRO / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", ASTRO / name)


if __name__ == "__main__":
    main(Path(sys.argv[1]))
